import { chromium } from 'playwright';
import fs from 'fs';
const browser = await chromium.launch();
const ctx = await browser.newContext({ userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36' });
const page = await ctx.newPage();
await page.goto('https://www.alza.cz/', { waitUntil: 'domcontentloaded', timeout: 90000 });
await page.waitForTimeout(10000);
await page.addScriptTag({ content: "globalThis.process = { env: {}, cwd: () => '/', argv: [], platform: 'browser' };" });
await page.addScriptTag({ content: fs.readFileSync('/tmp/g4-bundle.js', 'utf8') });
const out = await page.evaluate(async () => {
  const { MobileApi, MobileAccount } = globalThis.__alza;
  const api = new MobileApi({ visitorId: crypto.randomUUID(), baseUrl: location.origin });
  const acc = new MobileAccount(api);
  const steps = [];
  const nav = await acc.chatNavigation();
  steps.push({ step: 'alza_chat_navigation (real dist code, in-page)', keys: Object.keys(nav ?? {}).slice(0, 8), initChatHref: nav?.chatbotInitializeChatAction?.href ?? null });
  const chat = await acc.chatSend({ page_type: 1, referrer: 'https://www.alza.cz/' });
  const c = chat?.configuration ?? {};
  steps.push({ step: 'alza_chat_send (real dist code, in-page)', configId: c.configId, teamName: c.teamName, welcomeText: c.welcomeText, sessionExist: c.sessionExist, showChat: chat?.showChat, allowTextInput: c.allowTextInput });
  const zips = await acc.webZipCodes('Hradec Králové');
  const v = String(zips?.Value ?? '');
  steps.push({ step: 'alza_mobile_read web_zip_codes (real dist code, in-page)', errorLevel: zips?.ErrorLevel ?? null, valueIsHtml: v.startsWith('<div'), firstDataText: v.match(/data-text="([^"]+)"/)?.[1] ?? null, firstDataCity: v.match(/data-city="([^"]+)"/)?.[1] ?? null });
  return steps;
});
fs.writeFileSync('/tmp/p2-typed-e2e.json', JSON.stringify({ date: '2026-09-09', stack: 'compiled dist/ modules (esbuild bundle) executed in the live page', steps: out }, null, 1));
console.log(JSON.stringify(out, null, 1).slice(0, 1200));
await browser.close();
