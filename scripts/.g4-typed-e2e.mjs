import { chromium } from 'playwright';
import fs from 'fs';
const browser = await chromium.launch();
const ctx = await browser.newContext({ userAgent: 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/138.0.0.0 Safari/537.36' });
const page = await ctx.newPage();
await page.goto('https://www.alza.cz/', { waitUntil: 'domcontentloaded', timeout: 90000 });
await page.waitForTimeout(10000);
await page.addScriptTag({ content: "globalThis.process = { env: {}, cwd: () => '/', argv: [], platform: 'browser' };" });
await page.addScriptTag({ content: fs.readFileSync('/tmp/g4-bundle.js', 'utf8') });
const out = await page.evaluate(async () => {
  const { MobileApi, MobileAccount } = globalThis.__alza;
  const api = new MobileApi({ visitorId: crypto.randomUUID(), baseUrl: location.origin });
  const acc = new MobileAccount(api);
  const steps = [];
  const added = await acc.webAddToCart({ commodity_id: 5303618, count: 1 });
  steps.push({ step: 'alza_web_add_to_cart (real dist code, in-page)', basket_id: added.basket_id, item_id: added.item_id, responseKeys: Object.keys(added.response ?? {}) });
  const cart = await acc.webCart(added.basket_id);
  const cc = cart.cart ?? {};
  steps.push({ step: 'alza_web_cart (real dist code, in-page)', cartKeys: Object.keys(cc).slice(0, 10), maxStep: cc.maxStep, itemCount: Array.isArray(cart.items?.items) ? cart.items.items.length : undefined, firstItem: Array.isArray(cart.items?.items) ? { productId: cart.items.items[0]?.productId, count: cart.items.items[0]?.count, basketItemId: cart.items.items[0]?.basketItemId } : undefined });
  const delivery = await acc.deliveryOptions();
  steps.push({ step: 'alza_delivery_options (v13 typed, same stack)', deliveryGroups: Array.isArray(delivery?.deliveryGroups) ? delivery.deliveryGroups.length : undefined, firstGid: delivery?.deliveryGroups?.[0]?.deliveryGroupId ?? undefined, keys: Object.keys(delivery ?? {}).slice(0, 6) });
  return steps;
});
fs.writeFileSync('/tmp/g4-typed-e2e.json', JSON.stringify({ date: '2026-09-09', stack: 'compiled dist/ modules (esbuild bundle) executed in the live page', steps: out }, null, 1));
console.log(JSON.stringify(out, null, 1).slice(0, 1400));
await browser.close();
